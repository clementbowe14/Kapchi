import { createHash } from "node:crypto";
import { ACTIVE_POLICY_BUNDLE } from "./generated-policy-manifest.js";

export const policyDocumentKeys = ["shipping", "returns", "privacy", "terms"] as const;
export type PolicyDocumentKey = (typeof policyDocumentKeys)[number];
export type PolicyDocumentRole = "agreement" | "acknowledgment" | "notice";

export type PolicyDocumentMetadata = {
  digest: string;
  key: PolicyDocumentKey;
  path: string;
  role: PolicyDocumentRole;
  title: string;
  version: string;
};

export type PolicyBundle = {
  bundleVersion: string;
  checkoutStatement: { digest: string; version: string };
  documents: PolicyDocumentMetadata[];
  effectiveDate: string;
  schemaVersion: 1;
};

export type PolicyAssertion = {
  bundleVersion: string;
  returnsAcknowledged: true;
  termsAgreed: true;
};

export type CustomerPolicySnapshot = {
  bundleVersion: string;
  checkoutStatement: { digest: string; version: string };
  documents: Array<Omit<PolicyDocumentMetadata, "title">>;
  effectiveDate: string;
  schemaVersion: 1;
  statementSubmittedAt: string;
};

export type PersistedPolicyAssertionRow = {
  assertions: unknown;
  bundle_version: string;
  checkout_statement_digest: string;
  checkout_statement_version: string;
  documents: unknown;
  effective_date: Date | string;
  schema_version: number;
  statement_submitted_at: Date | string;
};

function canonicalJson(value: unknown): string {
  if (Array.isArray(value)) {
    return `[${value.map(canonicalJson).join(",")}]`;
  }
  if (value && typeof value === "object") {
    return `{${Object.entries(value as Record<string, unknown>)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([key, entry]) => `${JSON.stringify(key)}:${canonicalJson(entry)}`)
      .join(",")}}`;
  }
  return JSON.stringify(value);
}

function assertDigest(value: unknown, label: string): asserts value is string {
  if (typeof value !== "string" || !/^[a-f0-9]{64}$/.test(value)) {
    throw new Error(`Invalid generated policy ${label}.`);
  }
}

function validateGeneratedBundle(value: unknown): PolicyBundle {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error("Invalid generated policy bundle.");
  }

  const bundle = value as Partial<PolicyBundle>;
  if (
    bundle.schemaVersion !== 1 ||
    typeof bundle.bundleVersion !== "string" ||
    bundle.bundleVersion.length === 0 ||
    bundle.bundleVersion.length > 64 ||
    typeof bundle.effectiveDate !== "string" ||
    !/^\d{4}-\d{2}-\d{2}$/.test(bundle.effectiveDate) ||
    !bundle.checkoutStatement ||
    typeof bundle.checkoutStatement.version !== "string" ||
    bundle.checkoutStatement.version.length === 0 ||
    bundle.checkoutStatement.version.length > 64 ||
    !Array.isArray(bundle.documents) ||
    bundle.documents.length !== policyDocumentKeys.length
  ) {
    throw new Error("Invalid generated policy bundle metadata.");
  }

  assertDigest(bundle.checkoutStatement.digest, "checkout statement digest");
  const seen = new Set<string>();
  for (const document of bundle.documents) {
    if (
      !document ||
      !policyDocumentKeys.includes(document.key) ||
      seen.has(document.key) ||
      typeof document.title !== "string" ||
      document.title.length === 0 ||
      !["agreement", "acknowledgment", "notice"].includes(document.role) ||
      typeof document.version !== "string" ||
      document.version.length === 0 ||
      document.version.length > 64 ||
      typeof document.path !== "string" ||
      !document.path.startsWith("/policies/")
    ) {
      throw new Error("Invalid generated policy document metadata.");
    }
    assertDigest(document.digest, `${document.key} digest`);
    seen.add(document.key);
  }

  const roles = new Map(bundle.documents.map((document) => [document.key, document.role]));
  if (
    roles.get("terms") !== "agreement" ||
    roles.get("returns") !== "acknowledgment" ||
    roles.get("shipping") !== "notice" ||
    roles.get("privacy") !== "notice"
  ) {
    throw new Error("Invalid generated policy document roles.");
  }

  return bundle as PolicyBundle;
}

// This import is generated by the repository policy pipeline and intentionally
// remains the only backend source of active policy metadata.
export const activePolicyBundle = Object.freeze(
  validateGeneratedBundle(ACTIVE_POLICY_BUNDLE),
);

export const activePolicyBundleEtag = `"${createHash("sha256")
  .update(canonicalJson(activePolicyBundle))
  .digest("hex")}"`;

export function publicPolicyBundle() {
  return activePolicyBundle;
}

export function snapshotForInsertion() {
  return {
    assertions: { returnsAcknowledged: true, termsAgreed: true },
    bundleVersion: activePolicyBundle.bundleVersion,
    checkoutStatement: activePolicyBundle.checkoutStatement,
    documents: activePolicyBundle.documents.map(({ title: _title, ...document }) => document),
    effectiveDate: activePolicyBundle.effectiveDate,
    schemaVersion: activePolicyBundle.schemaVersion
  } as const;
}

function iso(value: Date | string) {
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) {
    throw new Error("Invalid persisted policy timestamp.");
  }
  return date.toISOString();
}

export function serializePolicySnapshot(
  row: PersistedPolicyAssertionRow | null | undefined,
): CustomerPolicySnapshot | null {
  if (!row) {
    return null;
  }

  const documents = row.documents;
  const assertions = row.assertions;
  if (
    row.schema_version !== 1 ||
    typeof row.bundle_version !== "string" ||
    row.bundle_version.length < 1 ||
    row.bundle_version.length > 64 ||
    typeof row.checkout_statement_version !== "string" ||
    row.checkout_statement_version.length < 1 ||
    row.checkout_statement_version.length > 64 ||
    !Array.isArray(documents) ||
    documents.length !== 4 ||
    !assertions ||
    typeof assertions !== "object" ||
    Array.isArray(assertions) ||
    JSON.stringify(
      Object.entries(assertions as Record<string, unknown>).sort(([left], [right]) =>
        left.localeCompare(right),
      ),
    ) !==
      JSON.stringify([
        ["returnsAcknowledged", true],
        ["termsAgreed", true]
      ])
  ) {
    throw new Error("Invalid persisted policy assertion.");
  }
  assertDigest(row.checkout_statement_digest, "persisted checkout statement digest");

  const expectedRoles = new Map<PolicyDocumentKey, PolicyDocumentRole>([
    ["shipping", "notice"],
    ["returns", "acknowledgment"],
    ["privacy", "notice"],
    ["terms", "agreement"]
  ]);
  const seen = new Set<string>();
  for (const value of documents) {
    if (!value || typeof value !== "object" || Array.isArray(value)) {
      throw new Error("Invalid persisted policy document.");
    }
    const document = value as Record<string, unknown>;
    if (
      Object.keys(document).length !== 5 ||
      !policyDocumentKeys.includes(document.key as PolicyDocumentKey) ||
      seen.has(document.key as string) ||
      document.role !== expectedRoles.get(document.key as PolicyDocumentKey) ||
      typeof document.version !== "string" ||
      document.version.length < 1 ||
      document.version.length > 64 ||
      typeof document.path !== "string" ||
      !document.path.startsWith("/policies/")
    ) {
      throw new Error("Invalid persisted policy document.");
    }
    assertDigest(document.digest, "persisted document digest");
    seen.add(document.key as string);
  }

  return {
    bundleVersion: row.bundle_version,
    checkoutStatement: {
      digest: row.checkout_statement_digest,
      version: row.checkout_statement_version
    },
    documents: documents as CustomerPolicySnapshot["documents"],
    effectiveDate:
      row.effective_date instanceof Date
        ? row.effective_date.toISOString().slice(0, 10)
        : String(row.effective_date).slice(0, 10),
    schemaVersion: row.schema_version,
    statementSubmittedAt: iso(row.statement_submitted_at)
  };
}
