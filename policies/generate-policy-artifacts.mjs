import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const policyRoot = join(root, "policies");
const archiveRoot = join(policyRoot, "archive");
const clientOutput = join(root, "client", "content", "generated-policy-manifest.ts");
const backendOutput = join(root, "backend", "src", "modules", "policies", "generated-policy-manifest.ts");
const VERSION = /^\d{4}-\d{2}-\d{2}\.[1-9]\d*$/;
const KEYS = ["shipping", "returns", "privacy", "terms"];
const ROLES = {
  shipping: "notice",
  returns: "acknowledgment",
  privacy: "notice",
  terms: "agreement",
};

function canonical(value) {
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${canonical(value[key])}`).join(",")}}`;
  }
  return JSON.stringify(value);
}

function digest(value) {
  return createHash("sha256").update(canonical(value)).digest("hex");
}

function assertRelease(release, filename) {
  if (release.schemaVersion !== 1 || !VERSION.test(release.bundleVersion) || release.bundleVersion !== filename.replace(/\.json$/, "")) {
    throw new Error(`Invalid bundle metadata in ${filename}`);
  }
  if (!['draft', 'approved'].includes(release.publicationStatus) || !/^\d{4}-\d{2}-\d{2}$/.test(release.effectiveDate)) {
    throw new Error(`Invalid publication metadata in ${filename}`);
  }
  if (!release.checkoutStatement || !VERSION.test(release.checkoutStatement.version) || typeof release.checkoutStatement.text !== "string") {
    throw new Error(`Invalid checkout statement in ${filename}`);
  }
  if (!Array.isArray(release.documents) || release.documents.length !== KEYS.length) {
    throw new Error(`Expected exactly four ordered documents in ${filename}`);
  }
  release.documents.forEach((document, index) => {
    if (document.key !== KEYS[index] || document.role !== ROLES[document.key] || !VERSION.test(document.version)) {
      throw new Error(`Invalid document order, role, or version in ${filename}`);
    }
    if (!document.title || !document.summary || !Array.isArray(document.sections) || document.sections.length === 0) {
      throw new Error(`Incomplete document ${document.key} in ${filename}`);
    }
  });
}

const activePointer = JSON.parse(await readFile(join(policyRoot, "active.json"), "utf8"));
const archiveFiles = (await readdir(archiveRoot)).filter((name) => name.endsWith(".json")).sort();
const releases = [];
for (const filename of archiveFiles) {
  const release = JSON.parse(await readFile(join(archiveRoot, filename), "utf8"));
  assertRelease(release, filename);
  releases.push({
    ...release,
    checkoutStatement: { ...release.checkoutStatement, digest: digest(release.checkoutStatement.text) },
    documents: release.documents.map((document) => ({
      ...document,
      digest: digest({
        key: document.key,
        role: document.role,
        sections: document.sections,
        summary: document.summary,
        title: document.title,
        version: document.version,
      }),
      path: `/policies/${document.key}/${document.version}`,
    })),
  });
}

const active = releases.find((release) => release.bundleVersion === activePointer.bundleVersion);
if (!active) throw new Error(`Active bundle ${activePointer.bundleVersion} is not archived`);

const clientArtifact = `// Generated by policies/generate-policy-artifacts.mjs. Do not edit.\n\nexport const POLICY_RELEASES = ${JSON.stringify(releases, null, 2)} as const;\n\nexport const ACTIVE_POLICY_RELEASE = POLICY_RELEASES.find((release) => release.bundleVersion === ${JSON.stringify(active.bundleVersion)})!;\n`;
const backendManifest = {
  schemaVersion: active.schemaVersion,
  bundleVersion: active.bundleVersion,
  effectiveDate: active.effectiveDate,
  checkoutStatement: {
    version: active.checkoutStatement.version,
    digest: active.checkoutStatement.digest,
  },
  documents: active.documents.map(({ key, title, role, version, digest, path }) => ({ key, title, role, version, digest, path })),
};
const backendArtifact = `// Generated by policies/generate-policy-artifacts.mjs. Do not edit.\n\nexport const ACTIVE_POLICY_BUNDLE = ${JSON.stringify(backendManifest, null, 2)} as const;\n`;

await writeFile(clientOutput, clientArtifact);
await writeFile(backendOutput, backendArtifact);
console.log(`Generated ${releases.length} policy release(s); active bundle ${active.bundleVersion} is ${active.publicationStatus}.`);
